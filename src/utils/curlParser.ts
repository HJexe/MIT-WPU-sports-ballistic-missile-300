import { ReverseEngineeredEndpoint } from '../types';

export function parseCurlCommand(curlStr: string): Partial<ReverseEngineeredEndpoint> | null {
  if (!curlStr || typeof curlStr !== 'string') return null;

  try {
    const trimmed = curlStr.trim();
    if (!trimmed.startsWith('curl')) {
      // If user pasted direct URL or JSON, handle gracefully
      if (trimmed.startsWith('http')) {
        return {
          url: trimmed,
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          sourceType: 'manual',
        };
      }
    }

    // Extract URL
    let urlMatch = trimmed.match(/curl\s+(?:'|")?([^'"\s]+)(?:'|")?/);
    if (!urlMatch) {
      urlMatch = trimmed.match(/--location\s+(?:'|")?([^'"\s]+)(?:'|")?/);
    }
    const url = urlMatch ? urlMatch[1] : 'https://sports.mitwpu.edu.in/api/v1/sports/slots/reserve';

    // Extract Method
    let method: 'POST' | 'GET' | 'PUT' = 'POST';
    const methodMatch = trimmed.match(/-X\s+([A-Z]+)/i) || trimmed.match(/--request\s+([A-Z]+)/i);
    if (methodMatch) {
      method = methodMatch[1].toUpperCase() as any;
    }

    // Extract Headers
    const headers: Record<string, string> = {};
    const headerRegex = /(?:-H|--header)\s+['"]([^'"]+)['"]/g;
    let match: RegExpExecArray | null;
    let cookieString = '';

    while ((match = headerRegex.exec(trimmed)) !== null) {
      const headerLine = match[1];
      const colonIdx = headerLine.indexOf(':');
      if (colonIdx > 0) {
        const key = headerLine.substring(0, colonIdx).trim();
        const val = headerLine.substring(colonIdx + 1).trim();
        headers[key] = val;

        if (key.toLowerCase() === 'cookie') {
          cookieString = val;
        }
      }
    }

    // Extract Data / Body
    let bodyTemplate = '';
    const dataMatch = trimmed.match(/(?:-d|--data|--data-raw)\s+['"]([\s\S]*?)['"](?:\s+-[A-Za-z]|\s*$)/);
    if (dataMatch) {
      bodyTemplate = dataMatch[1];
    }

    return {
      url,
      method,
      headers,
      cookieString,
      bodyTemplate,
      sourceType: 'curl_paste',
    };
  } catch (err) {
    console.error('Failed to parse cURL command:', err);
    return null;
  }
}

export function generateTypeScriptApiClient(endpoint: ReverseEngineeredEndpoint): string {
  const headersObj = JSON.stringify(endpoint.headers, null, 2);

  return `/**
 * Generated by kalil0321/reverse-api-engineer Engine
 * Target: ${endpoint.url}
 */

export interface CourtsideReservePayload {
  facility_id?: string;
  court_id?: string;
  slot_time?: string;
  date: string;
  [key: string]: any;
}

export class CourtsideApiClient {
  private baseUrl: string = "${endpoint.url}";
  private headers: HeadersInit = ${headersObj};

  async reserveSlotBurst(payload: CourtsideReservePayload, concurrency: number = 3): Promise<{ success: boolean; latencyMs: number; data?: any }> {
    const tStart = performance.now();
    const requests = Array.from({ length: concurrency }, (_, idx) => 
      fetch(this.baseUrl, {
        method: "${endpoint.method}",
        headers: this.headers,
        body: JSON.stringify({ ...payload, burst_index: idx, client_ts: Date.now() }),
      }).then(r => r.json())
    );

    try {
      const results = await Promise.allSettled(requests);
      const latencyMs = Math.round(performance.now() - tStart);
      const winner = results.find(r => r.status === 'fulfilled');

      return {
        success: !!winner,
        latencyMs,
        data: winner && winner.status === 'fulfilled' ? winner.value : undefined
      };
    } catch (e) {
      return { success: false, latencyMs: Math.round(performance.now() - tStart) };
    }
  }
}
`;
}

export function generatePythonAsyncClient(endpoint: ReverseEngineeredEndpoint): string {
  return `"""
Generated by kalil0321/reverse-api-engineer Engine
High-Speed Concurrency Slot Sniper Client
"""
import asyncio
import aiohttp
import time
import json

TARGET_URL = "${endpoint.url}"
HEADERS = ${JSON.stringify(endpoint.headers, null, 4)}

async def fire_single_reserve(session, burst_id, payload):
    t0 = time.perf_counter()
    try:
        async with session.post(TARGET_URL, json=payload, headers=HEADERS, timeout=3.0) as resp:
            data = await resp.json()
            latency_ms = round((time.perf_counter() - t0) * 1000)
            print(f"[BURST {burst_id}] Status {resp.status} in {latency_ms}ms: {data}")
            return {"status": resp.status, "data": data, "latency_ms": latency_ms}
    except Exception as e:
        print(f"[BURST {burst_id}] Failed: {e}")
        return None

async def execute_sniper_drop(payload, burst_count=3):
    print(f"[*] Dispatching {burst_count}x async burst to {TARGET_URL}...")
    async with aiohttp.ClientSession() as session:
        tasks = [fire_single_reserve(session, i, payload) for i in range(burst_count)]
        results = await asyncio.gather(*tasks)
        return results

if __name__ == "__main__":
    test_payload = {
        "sport": "badminton",
        "court": "badm_c1",
        "date": "2026-10-31",
        "time": "17:00-18:00"
    }
    asyncio.run(execute_sniper_drop(test_payload, burst_count=3))
`;
}
